const fs = require("fs");
const path = require("path");

function walk(dir) {
  let results = [];
  const list = fs.readdirSync(dir);
  list.forEach(file => {
    const fullPath = path.join(dir, file);
    const stat = fs.statSync(fullPath);
    if (stat && stat.isDirectory()) {
      results = results.concat(walk(fullPath));
    } else {
      if (file.toLowerCase().includes("ffmpeg") || file.toLowerCase().includes("ffprobe")) {
        results.push(fullPath);
      }
    }
  });
  return results;
}

try {
  const matches = walk(path.join(__dirname, "../node_modules"));
  console.log("Found matches in node_modules:", matches);
} catch (e) {
  console.error(e.message);
}
